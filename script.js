let lang = localStorage.getItem("zain-lang") || "en";
const body = document.body;
const langBtn = document.getElementById("langBtn");
const menuToggle = document.querySelector(".menu-toggle");
const nav = document.querySelector(".nav");

function applyLanguage() {
  const dict = translations[lang];
  document.documentElement.lang = lang;
  body.classList.toggle("rtl", lang === "ar");
  body.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.placeholder = dict[key];
  });
  langBtn.textContent = lang === "en" ? "عربي" : "EN";
  localStorage.setItem("zain-lang", lang);
}

langBtn.addEventListener("click", () => {
  lang = lang === "en" ? "ar" : "en";
  applyLanguage();
});

menuToggle.addEventListener("click", () => {
  const open = nav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(open));
});
nav.querySelectorAll("a").forEach(a => a.addEventListener("click", () => nav.classList.remove("open")));

const sections = [...document.querySelectorAll("main section[id]")];
const navLinks = [...document.querySelectorAll(".nav a")];
const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      navLinks.forEach(a => a.classList.toggle("active", a.getAttribute("href") === "#" + entry.target.id));
    }
  });
}, {rootMargin:"-35% 0px -55% 0px", threshold:0});
sections.forEach(s => observer.observe(s));

document.getElementById("quoteForm").addEventListener("submit", e => {
  e.preventDefault();
  const msg = lang === "ar" ? "تم استلام الطلب في هذه النسخة التجريبية. اربط النموذج ببريدك أو Formspree قبل النشر." : "Your request is captured in this demo. Connect the form to your email or Formspree before publishing.";
  alert(msg);
});

applyLanguage();
